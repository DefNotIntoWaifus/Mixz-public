#!/usr/bin/env python3
"""Tuning data for plan step 6: a train split and a validation split per kind, from pinned
sources that the benchmark test set does not use.

  data.py --pin      download every source and write its sha256 into sources.json
  data.py --freeze   choose the files and write sets.json
  data.py            make sure every file of sets.json is in the cache

Each source belongs to one split (sources.json 'split'), so a project is never in both. Files are
taken like the test set (tools/harness/fetch.py): a fixed order that balances bytes over sources,
up to a budget per kind, files above the primer-overlap limit dropped, and also every file whose
content is in the harness test set. Uses the harness cache ($MIXZ_CACHE or ~/.cache/mixz).
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "harness"))
import fetch  # noqa: E402

SOURCES = os.path.join(HERE, "sources.json")
SETS = os.path.join(HERE, "sets.json")
SPLITS = ("train", "valid")
KIB = 1024
BUDGET = {k: 1024 * KIB for k in ("py", "c", "js", "json", "web", "prose")}
BUDGET.update(man=512 * KIB, elf=4096 * KIB, png=3072 * KIB)


def load_sources() -> dict:
    with open(SOURCES) as f:
        return json.load(f)


def harness_hashes() -> set:
    with open(fetch.SETS) as f:
        return {e["sha256"] for ks in json.load(f)["kinds"].values() for e in ks["files"]}


def freeze(sources: dict) -> dict:
    test = harness_hashes()
    sets = {"comment": "Frozen tuning sets, generated by tools/tuner/data.py --freeze. Do not edit by hand.",
            "overlap_k": fetch.overlap.K, "max_overlap": fetch.overlap.MAX_OVERLAP, "budgets": BUDGET, "kinds": {}}
    for split in SPLITS:
        cands = fetch.candidates({"sources": [s for s in sources["sources"] if s["split"] == split]})
        for kind in fetch.KINDS:
            chosen, taken, dropped, total = [], set(), {"overlap": 0, "in_test_set": 0}, 0
            for sid, name, n, sha in cands[kind]:
                if sha in taken or total + n > BUDGET[kind]:
                    continue
                if sha in test:
                    dropped["in_test_set"] += 1
                    continue
                with open(fetch.file_path(sid, name), "rb") as f:
                    ov = fetch.primer_overlap(kind, f.read())
                if ov > fetch.overlap.MAX_OVERLAP:
                    dropped["overlap"] += 1
                    continue
                taken.add(sha)
                chosen.append({"source": sid, "path": name, "bytes": n, "sha256": sha, "overlap": round(ov, 4)})
                total += n
            sets["kinds"].setdefault(kind, {})[split] = {"files": chosen, "dropped": dropped}
            srcs = sorted({e["source"] for e in chosen})
            print(f"{kind:5s} {split}: {len(chosen):4d} files {total / 1e6:5.2f} MB from {len(srcs)} sources; "
                  f"dropped {dropped['overlap']} for overlap, {dropped['in_test_set']} in the test set", flush=True)
    return sets


def write_sets(sets: dict) -> None:
    lines = ["{"] + [f" {json.dumps(k)}: {json.dumps(v)}," for k, v in sets.items() if k != "kinds"] + [' "kinds": {']
    kinds = list(sets["kinds"].items())
    for i, (kind, ks) in enumerate(kinds):
        lines.append(f"  {json.dumps(kind)}: {{")
        for j, split in enumerate(SPLITS):
            rows = [f"    {json.dumps(e)}" for e in ks[split]["files"]]
            lines.append(f'   "{split}": {{"dropped": {json.dumps(ks[split]["dropped"])}, "files": ['
                         + ("\n" + ",\n".join(rows) + "\n   " if rows else "") + "]}" + ("," if j == 0 else ""))
        lines.append("  }" + ("," if i < len(kinds) - 1 else ""))
    lines += [" }", "}"]
    with open(SETS, "w") as f:
        f.write("\n".join(lines) + "\n")


def ensure(split: str = None) -> list:
    """Every file of the split (both when None) in the cache; entries with 'kind', 'split' and 'abs'."""
    with open(SETS) as f:
        sets = json.load(f)
    srcs = {s["id"]: s for s in load_sources()["sources"]}
    out = [dict(e, kind=kind, split=sp, abs=fetch.file_path(e["source"], e["path"]))
           for kind, ks in sets["kinds"].items() for sp in SPLITS if split in (None, sp) for e in ks[sp]["files"]]
    need = {e["source"] for e in out if not os.path.exists(e["abs"]) or os.path.getsize(e["abs"]) != e["bytes"]}
    for sid in sorted(need):
        idx = os.path.join(fetch.cache_dir(), "sets", sid, ".index.json")
        if os.path.exists(idx):
            os.remove(idx)
        fetch.extract(srcs[sid])
    for e in out:
        with open(e["abs"], "rb") as f:
            if fetch.sha256_bytes(f.read()) != e["sha256"]:
                raise SystemExit(f"{e['source']}/{e['path']}: content differs from sets.json")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pin", action="store_true")
    ap.add_argument("--freeze", action="store_true")
    args = ap.parse_args()
    sources = load_sources()
    if args.pin:
        for src in sources["sources"]:
            fetch.download(src, pin=True)
        with open(SOURCES, "w") as f:
            json.dump(sources, f, indent=1)
            f.write("\n")
        print("sha256 pinned in sources.json")
    if args.freeze:
        write_sets(freeze(sources))
        print(f"wrote {SETS}")
    if not (args.pin or args.freeze):
        print(f"{len(ensure())} files ready in {fetch.cache_dir()}")


if __name__ == "__main__":
    main()
